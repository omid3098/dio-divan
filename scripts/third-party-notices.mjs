// Generate notices from the modules the web build actually includes. Missing license text fails the build.
import assert from 'node:assert/strict';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');

function packageAt(file) {
  let folder = dirname(file.split('?')[0]);
  while (folder !== dirname(folder)) {
    const manifest = join(folder, 'package.json');
    if (existsSync(manifest)) return { folder, ...JSON.parse(readFileSync(manifest, 'utf8')) };
    folder = dirname(folder);
  }
  throw new Error(`No package manifest for bundled module: ${file}`);
}

export function thirdPartyNotices(cssPlugins) {
  const cssFiles = new Set();
  // Vite 8 has addWatchFile but no getWatchFiles: retain the CSS processor's resolved dependencies.
  const processors = cssPlugins.map((plugin) => {
    if (!plugin.transform) return plugin;
    const hook = plugin.transform;
    const handler = typeof hook === 'function' ? hook : hook.handler;
    const transform = function (...args) {
      const context = this;
      const tracked = new Proxy(context, {
        get(target, key) {
          if (key === 'addWatchFile')
            return (file) => {
              cssFiles.add(file);
              context.addWatchFile(file);
            };
          return Reflect.get(target, key, target);
        },
      });
      return handler.apply(tracked, args);
    };
    return {
      ...plugin,
      transform: typeof hook === 'function' ? transform : { ...hook, handler: transform },
    };
  });
  return [
    ...processors,
    {
      name: 'third-party-notices',
      generateBundle() {
        const packages = new Map();
        // CSS processors register resolved imports as watched files, outside the JS module graph.
        const bundled = [
          ...this.getModuleIds(),
          ...[...cssFiles].filter((file) => /\.(?:css|woff2?|ttf|otf)(?:\?|$)/u.test(file)),
        ];
        for (const id of bundled) {
          if (!id.includes('node_modules') || id.startsWith('\0')) continue;
          const pkg = packageAt(id);
          packages.set(`${pkg.name}@${pkg.version}`, pkg);
        }
        assert.ok(packages.size > 2, 'The web bundle must supply its library module list');
        assert.ok(
          [...packages.values()].some((pkg) => pkg.name === 'tw-animate-css'),
          'The web bundle must supply CSS-only dependencies',
        );
        const missing = [];
        const sections = [...packages]
          .sort(([a], [b]) => a.localeCompare(b))
          .map(([name, pkg]) => {
            const files = readdirSync(pkg.folder).filter((file) =>
              /^(?:licen[cs]e|copying|copyright|notice)(?:[._-].*)?$/iu.test(file),
            );
            const upstream = join(root, 'scripts', 'licenses', `${name.replaceAll('/', '__')}.txt`);
            if (
              !files.some((file) => /^(?:licen[cs]e|copying)/iu.test(file)) &&
              !existsSync(upstream)
            )
              missing.push(name);
            return `## ${name}\n\nLicense: ${pkg.license ?? 'see text below'}\n\n${files
              .sort()
              .map((file) => readFileSync(join(pkg.folder, file), 'utf8').trim())
              .join(
                '\n\n',
              )}${existsSync(upstream) ? `\n\n${readFileSync(upstream, 'utf8').trim()}` : ''}\n`;
          });
        assert.equal(missing.length, 0, `Missing license text: ${missing.join(', ')}`);
        const notices =
          '# Third-party notices\n\nGenerated by the web build from its bundled modules, CSS imports and assets. Do not edit by hand.\n\n' +
          sections.join('\n');
        for (const name of packages.keys())
          assert.ok(notices.includes(`## ${name}\n`), `Missing notice: ${name}`);
        writeFileSync(join(root, 'THIRD-PARTY-NOTICES.md'), notices);
      },
    },
  ];
}
